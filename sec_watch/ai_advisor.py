"""Google Gemini AI Security Advisor for SEC WATCH."""

from __future__ import annotations

import json
import os
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any

DEFAULT_MODEL = "gemini-3.5-flash-lite"
GEMINI_API_URL = "https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={key}"


def get_api_key() -> str:
    """Retrieve Gemini API key from environment or local .env file."""
    # 1. Check process environment
    env_key = os.environ.get("GEMINI_API_KEY", "").strip()
    if env_key:
        return env_key

    # 2. Check local .env file
    env_file = Path(".env")
    if env_file.exists():
        try:
            for line in env_file.read_text(encoding="utf-8").splitlines():
                line = line.strip()
                if line and not line.startswith("#") and "=" in line:
                    key, _, val = line.partition("=")
                    if key.strip() == "GEMINI_API_KEY":
                        return val.strip().strip("'\"")
        except OSError:
            pass

    return ""


def is_available() -> bool:
    """Return True if an API key is configured."""
    return bool(get_api_key())


def query_gemini(prompt: str, model: str = DEFAULT_MODEL, timeout: float = 60.0) -> str:
    """Send a prompt to the Gemini API using standard library urllib."""
    api_key = get_api_key()
    if not api_key:
        raise RuntimeError("Gemini API key is not configured. Set GEMINI_API_KEY in .env.")

    url = GEMINI_API_URL.format(model=model, key=api_key)
    payload = {
        "contents": [
            {
                "parts": [{"text": prompt}]
            }
        ],
        "generationConfig": {
            "temperature": 0.2,
            "maxOutputTokens": 600,
        },
    }

    req = urllib.request.Request(
        url,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json", "User-Agent": "SEC-WATCH-Advisor/1.0"},
        method="POST",
    )

    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            candidates = data.get("candidates", [])
            if candidates:
                parts = candidates[0].get("content", {}).get("parts", [])
                if parts:
                    return str(parts[0].get("text", "")).strip()
            return "No response content generated by Gemini."
    except urllib.error.HTTPError as err:
        err_body = err.read().decode("utf-8", errors="replace")
        try:
            err_json = json.loads(err_body)
            msg = err_json.get("error", {}).get("message", err_body)
        except Exception:
            msg = err_body
        raise RuntimeError(f"Gemini API Error (HTTP {err.code}): {msg}") from err
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        raise RuntimeError(f"Gemini Connection Failed: {exc}") from exc


def explain_finding(finding: Any) -> str:
    """Generate in-depth remediation code and explanation for a specific finding."""
    prompt = (
        f"You are an expert offensive/defensive cybersecurity educator assessing an authorized lab.\n"
        f"Finding: {getattr(finding, 'title', str(finding))}\n"
        f"Severity: {getattr(finding, 'severity', 'Unknown')}\n"
        f"OWASP: {getattr(finding, 'owasp', 'N/A')}\n"
        f"CWE: {getattr(finding, 'cwe', 'N/A')}\n"
        f"Observed Evidence: {getattr(finding, 'evidence', 'N/A')}\n\n"
        f"Please provide:\n"
        f"1. A concise explanation of the security risk and attacker exploitability.\n"
        f"2. Practical code and server configuration snippets to fix this issue (e.g. for Nginx, Apache, or Python frameworks).\n"
        f"3. Verification command (e.g., using curl) to confirm the fix.\n"
        f"Keep the answer clear, professional, and beginner-friendly."
    )
    return query_gemini(prompt)


def generate_executive_summary(findings: list[Any], target: str) -> str:
    """Generate an AI executive assessment summary across all findings."""
    if not findings:
        return "No vulnerabilities were identified during this assessment. Good security hygiene!"

    order = {"High": 0, "Medium": 1, "Low": 2}
    sorted_findings = sorted(findings, key=lambda f: order.get(getattr(f, "severity", ""), 3))

    findings_summary = "\n".join(
        f"- [{getattr(f, 'severity', 'Info')}] {getattr(f, 'title', '')}: {getattr(f, 'evidence', '')[:120]}"
        for f in sorted_findings[:6]
    )

    prompt = (
        f"You are a Senior Web Security Consultant.\n"
        f"Write a 2-paragraph Executive Security Summary for an authorized assessment of target: {target}.\n"
        f"Key Findings Observed:\n{findings_summary}\n\n"
        f"Paragraph 1: Summarize the overall risk posture and primary exposure areas (files, transport, headers).\n"
        f"Paragraph 2: Provide a prioritized action plan for what to remediate first."
    )
    return query_gemini(prompt)

